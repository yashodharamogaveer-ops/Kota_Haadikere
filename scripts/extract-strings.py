#!/usr/bin/env python3
"""
One-time codemod + catalog generator.

Turns   lang === 'kn' ? 'ಕನ್ನಡ' : 'English'   (both plain string literals)
into    tx('ಕನ್ನಡ', 'English')
and writes src/lib/stringCatalog.ts so the admin panel can list & override every text.

Safe to re-run: already converted calls are left alone, and the catalog is rebuilt
from the existing tx('..','..') calls.
"""
import re, json, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
APP = ROOT / 'src' / 'App.tsx'
OUT = ROOT / 'src' / 'lib' / 'stringCatalog.ts'

Q = r"""(?:'(?:[^'\\\n]|\\.)*'|"(?:[^"\\\n]|\\.)*")"""
TERNARY = re.compile(r"lang\s*===\s*'kn'\s*\?\s*(" + Q + r")\s*:\s*(" + Q + r")")
TXCALL = re.compile(r"\btx\(\s*(" + Q + r")\s*,\s*(" + Q + r")\s*\)")

def decode(lit: str) -> str:
    body = lit[1:-1]
    out, i = [], 0
    while i < len(body):
        c = body[i]
        if c == '\\' and i + 1 < len(body):
            n = body[i + 1]
            if n == 'u' and re.match(r'[0-9a-fA-F]{4}', body[i + 2:i + 6]):
                out.append(chr(int(body[i + 2:i + 6], 16))); i += 6; continue
            out.append({'n': '\n', 't': '\t'}.get(n, n)); i += 2; continue
        out.append(c); i += 1
    return ''.join(out)

def fnv(s: str) -> str:
    """FNV-1a over UTF-16 code units — must match fnv1a() in src/lib/content.ts."""
    b = s.encode('utf-16-le')
    h = 0x811c9dc5
    for i in range(0, len(b), 2):
        h ^= b[i] | (b[i + 1] << 8)
        h = (h * 0x01000193) & 0xffffffff
    return format(h, '08x')

SECTION_MARKERS = [
    (re.compile(r"currentPage === 'home'"), 'Home'),
    (re.compile(r"currentPage === 'about'"), 'About'),
    (re.compile(r"currentPage === 'gallery'"), 'Gallery'),
    (re.compile(r"currentPage === 'seva'"), 'Sevas'),
    (re.compile(r"currentPage === 'contact'"), 'Contact'),
]

def main():
    src = APP.read_text(encoding='utf8')
    app_start = src.index('export default function App()')
    head, body = src[:app_start], src[app_start:]

    SKIP = {'ENGLISH', 'kn_IN'}  # language toggle label / locale codes are not editable texts

    def repl(m):
        if decode(m.group(1)) in SKIP:
            return m.group(0)
        # only convert when the ternary is a standalone expression (not part of && / || / ! chain)
        before = body[:m.start()].rstrip()
        prev = before[-1:] if before else ''
        if prev in ('&', '|', '!', '+', '-', '*', '/', '<', '>') and not before.endswith('=>') and not before.endswith('>'):
            return m.group(0)
        if before.endswith('&&') or before.endswith('||'):
            return m.group(0)
        return f"tx({m.group(1)}, {m.group(2)})"

    new_body = TERNARY.sub(repl, body)
    new_src = head + new_body
    APP.write_text(new_src, encoding='utf8')

    # --- build the catalog from all tx() calls ---
    entries, seen = [], set()
    lines = new_src.split('\n')
    # section by "currentPage === 'x'" markers: track the most recent marker above each line
    marker_at = []
    cur = 'General'
    for ln in lines:
        for rx, name in SECTION_MARKERS:
            if rx.search(ln) and ('&&' in ln or '{' in ln):
                cur = name
        if 'FOOTER' in ln and '{/*' in ln:
            cur = 'Footer'
        if 'FLOATING ACTION' in ln:
            cur = 'Floating buttons'
        if 'STICKY NAVBAR' in ln:
            cur = 'Header'
        marker_at.append(cur)

    for idx, ln in enumerate(lines):
        for m in TXCALL.finditer(ln):
            kn, en = decode(m.group(1)), decode(m.group(2))
            if kn == 'ENGLISH':  # language-toggle label, not an editable text
                continue
            key = fnv(kn + '\u0001' + en)
            if key in seen:
                continue
            seen.add(key)
            entries.append({'id': 's' + key, 'section': marker_at[idx], 'kn': kn, 'en': en})

    ts = ["// AUTO-GENERATED by scripts/extract-strings.py — do not edit by hand.",
          "// Every text in the public site that is not part of the main translations object.",
          "export interface CatalogEntry { id: string; section: string; kn: string; en: string }",
          "export const STRING_CATALOG: CatalogEntry[] = " + json.dumps(entries, ensure_ascii=False, indent=1) + ";", ""]
    OUT.write_text('\n'.join(ts), encoding='utf8')
    print(f"converted ternaries: {len(TERNARY.findall(body)) - len(TERNARY.findall(new_body))}, catalog entries: {len(entries)}")

if __name__ == '__main__':
    main()
